#!/usr/bin/env node
/*
 * Writes public/js/config.js from environment variables.
 *
 *   SUPABASE_URL        https://xxxx.supabase.co
 *   SUPABASE_ANON_KEY   the public "anon" / publishable key (safe to expose)
 *   GOOGLE_AUTH         "true" to show the "Continue with Google" button
 *
 * Netlify runs this as the build command. Locally you can either export the
 * variables first, or just edit public/js/config.js by hand.
 */
const fs = require("fs");
const path = require("path");

const file = path.join(__dirname, "..", "public", "js", "config.js");
const url = (process.env.SUPABASE_URL || "").trim();
const key = (process.env.SUPABASE_ANON_KEY || "").trim();
const google = String(process.env.GOOGLE_AUTH || "").toLowerCase() === "true";

const isPlaceholder = (s) => !s || /YOUR-/i.test(s);

function currentFileIsConfigured() {
  try {
    const src = fs.readFileSync(file, "utf8");
    return !/YOUR-PROJECT|YOUR-ANON/i.test(src);
  } catch (e) {
    return false;
  }
}

if (!isPlaceholder(url) && !isPlaceholder(key)) {
  if (!/^https:\/\/[a-z0-9-]+\.supabase\.(co|in)\/?$/i.test(url) && !/^https?:\/\/(localhost|127\.0\.0\.1)/i.test(url)) {
    console.warn("[build-config] SUPABASE_URL does not look like https://<ref>.supabase.co, continuing anyway.");
  }
  const body =
    "/* Generated by scripts/build-config.js. The anon key is public by design; Row Level Security protects the data. */\n" +
    "window.DESHIPAY_CONFIG = " +
    JSON.stringify({ supabaseUrl: url.replace(/\/$/, ""), supabaseAnonKey: key, googleAuth: google }, null, 2) +
    ";\n";
  fs.writeFileSync(file, body);
  console.log("[build-config] wrote public/js/config.js from environment variables");
} else if (currentFileIsConfigured()) {
  console.log("[build-config] environment variables not set, keeping the existing public/js/config.js");
} else if (process.env.NETLIFY) {
  // A site with no database is a supported configuration now: the landing offers
  // the no-login "Create my page" flow and pages can be downloaded as standalone
  // HTML. Make that an explicit choice so a missing/typo'd key still fails loudly.
  if (String(process.env.SITE_OFFLINE || "").toLowerCase() === "true") {
    console.warn(
      "\n[build-config] SITE_OFFLINE=true: no SUPABASE_URL / SUPABASE_ANON_KEY, keeping the placeholder " +
        "public/js/config.js.\n" +
        "[build-config] The site will run in offline mode (no accounts; \"Create my page\" + HTML download work).\n"
    );
  } else {
    console.error(
      "\n[build-config] SUPABASE_URL and SUPABASE_ANON_KEY are not set.\n" +
        "Add them in Netlify: Site configuration > Environment variables, then redeploy.\n" +
        "Or, to deploy the site without a database (offline mode only), set SITE_OFFLINE=true instead.\n"
    );
    process.exit(1);
  }
} else {
  console.warn(
    "[build-config] Supabase is not configured yet. Edit public/js/config.js or export SUPABASE_URL and SUPABASE_ANON_KEY."
  );
}
