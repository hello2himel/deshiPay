#!/usr/bin/env node
/*
 * Generates public/css/themes.css.
 *
 * Each theme is one accent colour (plus a lighter twin for dark mode). Every
 * other colour (background, borders, text, soft tints) is derived from it, so
 * the whole page feels tinted rather than just the buttons. Colours are written
 * out as plain hex, so there is no dependence on color-mix() in old browsers.
 *
 * To add a theme: add a line to THEMES, run `npm run themes`, and add the id to
 *   - THEMES in public/js/themes.js
 *   - the profiles_theme_valid check in, or a new migration next to, supabase/migrations/
 */
const fs = require("fs");
const path = require("path");

// accent must keep >= 4.5:1 contrast against white (button text);
// dark must keep >= 4.5:1 against the dark page background.
const THEMES = [
  // emerald is the site default (green scheme); the rest are user-selectable.
  // Deep "bottle" green chosen for the green migration: calmer than the bright
  // money/success greens, 6.5:1 white-on-accent, and clearly distinct from the
  // old rose and from bKash pink.
  { id: "emerald", accent: "#056B4E", dark: "#34D6A4", ok: "#0D7A30", okDark: "#7CE08B" },
  { id: "rose", accent: "#E2136E", dark: "#F0388B" },
  { id: "crimson", accent: "#C62432", dark: "#FF6F7A" },
  { id: "amber", accent: "#B45309", dark: "#F5A04A" },
  { id: "coffee", accent: "#7C4A2D", dark: "#D6A07A" },
  { id: "olive", accent: "#4D7C0F", dark: "#B1D05B" },
  { id: "teal", accent: "#0F766E", dark: "#3FCFC8" },
  { id: "ocean", accent: "#1D5FD0", dark: "#6CA6FF" },
  { id: "violet", accent: "#6D3FD9", dark: "#AD92FF" },
  { id: "graphite", accent: "#2E3A4B", dark: "#B6C1D1" }
];

// The page surfaces are tinted from the theme accent itself (not a neutral
// base), so the background follows the theme: rose -> pinkish white, emerald ->
// minty white, ocean -> bluish white, amber -> cream, graphite -> cool grey.
// Tints are mixed with white/black rather than a shared lavender base, which
// used to wash the hue out for every accent except the warm ones.
const LIGHT = {
  bg: "#FFFFFF", bgTint: 0.1,
  sunk: "#FFFFFF", sunkTint: 0.15,
  line: "#FFFFFF", lineTint: 0.28,
  ink: "#1B1226", inkTint: 0.12,
  muted: "#6B6478", mutedTint: 0.12
};
const DARK = {
  bg: "#100B17", bgTint: 0.1,
  panel: "#181120", panelTint: 0.08,
  sunk: "#221A2E", sunkTint: 0.12,
  line: "#392E48", lineTint: 0.18,
  ink: "#F4F0F8", inkTint: 0.05,
  muted: "#ABA1BA", mutedTint: 0.06
};

const rgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
const hex = (a) => "#" + a.map((v) => Math.round(v).toString(16).padStart(2, "0")).join("").toUpperCase();
const mix = (a, b, t) => {
  const x = rgb(a), y = rgb(b);
  return hex(x.map((v, i) => v * (1 - t) + y[i] * t));
};

function lightVars(t) {
  const a = t.accent;
  return [
    ["--bg", mix(LIGHT.bg, a, LIGHT.bgTint)],
    ["--panel", "#FFFFFF"],
    ["--sunk", mix(LIGHT.sunk, a, LIGHT.sunkTint)],
    ["--line", mix(LIGHT.line, a, LIGHT.lineTint)],
    ["--ink", mix(LIGHT.ink, a, LIGHT.inkTint)],
    ["--muted", mix(LIGHT.muted, a, LIGHT.mutedTint)],
    ["--accent", a],
    ["--on-accent", "#FFFFFF"],
    ["--accent-soft", mix("#FFFFFF", a, 0.15)],
    ["--accent-text", mix(a, "#000000", 0.1)],
    ["--ok", t.ok || "#0B7F58"],
    ["--ok-soft", "#DDF4EA"],
    ["--bad", "#C0262D"],
    ["--bad-soft", "#FBE6E7"],
    ["--shadow", "rgba(27, 18, 38, 0.32)"],
    ["--slip-accent", a],
    ["--slip-accent-soft", mix("#FFFFFF", a, 0.1)],
    ["color-scheme", "light"]
  ];
}

function darkVars(t) {
  const a = t.dark;
  return [
    ["--bg", mix(DARK.bg, a, DARK.bgTint)],
    ["--panel", mix(DARK.panel, a, DARK.panelTint)],
    ["--sunk", mix(DARK.sunk, a, DARK.sunkTint)],
    ["--line", mix(DARK.line, a, DARK.lineTint)],
    ["--ink", mix(DARK.ink, a, DARK.inkTint)],
    ["--muted", mix(DARK.muted, a, DARK.mutedTint)],
    ["--accent", a],
    ["--on-accent", "#17101F"],
    ["--accent-soft", mix(DARK.panel, a, 0.2)],
    ["--accent-text", a],
    ["--ok", t.okDark || "#3DD598"],
    ["--ok-soft", "#0F2F26"],
    ["--bad", "#FF8A8F"],
    ["--bad-soft", "#3A1618"],
    ["--shadow", "rgba(0, 0, 0, 0.6)"],
    ["--slip-accent", t.accent],
    ["--slip-accent-soft", mix("#FFFFFF", t.accent, 0.1)],
    ["color-scheme", "dark"]
  ];
}

const block = (sel, vars, indent) =>
  indent + sel + " {\n" + vars.map(([k, v]) => indent + "  " + k + ": " + v + ";").join("\n") + "\n" + indent + "}\n";

let css = "/* GENERATED by scripts/gen-themes.js. Do not edit by hand. */\n\n";
THEMES.forEach((t, i) => {
  const sel = (i === 0 ? ':root, ' : "") + '[data-theme="' + t.id + '"]';
  css += block(sel, lightVars(t), "");
});
css += "\n@media (prefers-color-scheme: dark) {\n";
THEMES.forEach((t, i) => {
  const sel = (i === 0 ? ':root, ' : "") + '[data-theme="' + t.id + '"]';
  css += block(sel, darkVars(t), "  ");
});
css += "}\n";

// Explicit light/dark choice from the nav toggle overrides the system preference.
css += "\n/* data-mode on <html> wins over prefers-color-scheme (theme toggle) */\n";
// Both the root and any nested theme scope (e.g. the PayView preview's own
// [data-theme] element) must follow the explicit mode, not the OS preference.
const modeSel = (mode, id) =>
  'html[data-mode="' + mode + '"][data-theme="' + id + '"], html[data-mode="' + mode + '"] [data-theme="' + id + '"]';
THEMES.forEach((t) => {
  css += block(modeSel("light", t.id), lightVars(t), "");
  css += block(modeSel("dark", t.id), darkVars(t), "");
});

fs.writeFileSync(path.join(__dirname, "..", "public", "css", "themes.css"), css);
console.log("wrote public/css/themes.css (" + THEMES.length + " themes)");

// quick contrast report so a bad accent is caught early
const lum = (h) => {
  const [r, g, b] = rgb(h).map((v) => { v /= 255; return v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4); });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const cr = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };
THEMES.forEach((t) => {
  const l = cr("#FFFFFF", t.accent), d = cr("#17101F", t.dark), dbg = cr(t.dark, mix(DARK.bg, t.dark, 0.05));
  const flag = l < 4.5 || d < 4.5 || dbg < 4.5 ? "  <-- LOW CONTRAST" : "";
  console.log(t.id.padEnd(9), "light button " + l.toFixed(1) + ":1", "dark button " + d.toFixed(1) + ":1", "dark text-on-page " + dbg.toFixed(1) + ":1" + flag);
});
