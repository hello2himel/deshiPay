test("a custom fontUrl replaces the Google Fonts link and \"\" removes it", () => {
  const custom = assets();
  custom.fontUrl = "https://fonts.example/custom.css";
  const html = E.buildPageHtml(full, custom);
  assert.ok(html.includes('href="https://fonts.example/custom.css"'));
  assert.strictEqual(count(html, '<link rel="stylesheet"'), 1, "still one stylesheet");
  // pay.html's font preconnects stay in the head, as in the recipe
  assert.strictEqual(count(html, 'rel="preconnect"'), 2);

  const none = assets();
  none.fontUrl = "";
  const plain = E.buildPageHtml(full, none);
  assert.strictEqual(plain.indexOf("fonts.googleapis.com"), -1);
  assert.strictEqual(plain.indexOf('rel="stylesheet"'), -1);
});

/* ---------------- safety guard for inlined assets ---------------- */

test("a literal </script in an inlined asset cannot close the script element early", () => {
  const broken = assets();
  broken.js.pay = 'var closing = "</script>"; var style = "</style>";';
  const html = E.buildPageHtml(full, broken);
  assert.strictEqual(html.indexOf('var closing = "</script>"'), -1, "literal sequence is guarded");
  assert.ok(html.includes('var closing = "<\\/script>";'), "escaped to <\\/script> (same JS string)");
  assert.strictEqual(count(html, "<script>"), 10);
  assert.strictEqual(count(html, "</script>"), 10);
});

