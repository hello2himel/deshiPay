let passed = 0;
const pending = [];
function pass(name) {
  passed++;
  console.log("  ok   " + name);
}
function fail(name, e) {
  console.error("  FAIL " + name + "\n       " + (e && e.message));
  process.exitCode = 1;
}
function test(name, fn) {
  try {
    const result = fn();
    if (result && typeof result.then === "function") {
      pending.push(result.then(() => pass(name), (e) => fail(name, e)));
      return;
    }
    pass(name);
  } catch (e) {
    fail(name, e);
  }
}

