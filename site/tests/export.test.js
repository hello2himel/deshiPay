  const at = MARKERS.css.map(([, marker]) => html.indexOf(marker));
  assert.deepStrictEqual(at, [...at].sort((a, b) => a - b), "CSS order themes -> base -> pay");
  assert.ok(at.every((n) => n >= 0));
